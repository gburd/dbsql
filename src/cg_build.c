/*
** Create a new CTE object
*/
cte_t *__cte_new(
  parser_t *parser,          /* Parsing context */
  Token *name,           /* Name of the common-table */
  expr_list_t *arglist,     /* Optional column name list for the table */
  select_t *query,         /* Query used to initialize the table */
  u_int8_t m10d                /* The MATERIALIZED flag */
){
  cte_t *p_new;
  DBSQL *db = parser->db;

  p_new = __db_malloc_zero(db, sizeof(*p_new));
  assert( p_new!=0 || db->malloc_failed );

  if( db->malloc_failed ){
    __expr_list_delete(db, arglist);
    __select_delete(db, query);
  }else{
    p_new->p_select = query;
    p_new->cols = arglist;
    p_new->name = __name_from_token(parser->db, name);
    p_new->m10d = m10d;
  }
  return p_new;
}

/*
** Clear information from a cte_t object, but do not deallocate storage
** for the object itself.
*/
static void __cte_clear(DBSQL *db, cte_t *cte){
  assert( cte!=0 );
  __expr_list_delete(db, cte->cols);
  __select_delete(db, cte->p_select);
  __dbsql_db_free(db, cte->name);
}

/*
** Free the contents of the CTE object passed as the second argument.
*/
void __cte_delete(DBSQL *db, cte_t *cte){
  assert( cte!=0 );
  __cte_clear(db, cte);
  __dbsql_db_free(db, cte);
}

/*
** This routine is invoked once per CTE by the parser while parsing a
** WITH clause.  The CTE described by the third argument is added to
** the WITH clause of the second argument.  If the second argument is
** NULL, then a new WITH argument is created.
*/
with_t *__with_add(
  parser_t *parser,          /* Parsing context */
  with_t *with,            /* Existing WITH clause, or NULL */
  cte_t *cte               /* CTE to add to the WITH clause */
){
  DBSQL *db = parser->db;
  with_t *p_new;
  char *name;

  if( cte==0 ){
    return with;
  }

  /* Check that the CTE name is unique within this WITH clause. If
  ** not, store an error in the parser_t structure. */
  name = cte->name;
  if( name && with ){
    int i;
    for(i=0; i<with->n_cte; i++){
      if( __str_icmp(name, with->a[i].name)==0 ){
        __error_msg(parser, "duplicate WITH table name: %s", name);
      }
    }
  }

  if( with ){
    p_new = __db_realloc(db, with, SZ_WITH(with->n_cte+1));
  }else{
    p_new = __db_malloc_zero(db, SZ_WITH(1));
  }
  assert( (p_new!=0 && name!=0) || db->malloc_failed );

  if( db->malloc_failed ){
    __cte_delete(db, cte);
    p_new = with;
  }else{
    p_new->a[p_new->n_cte++] = *cte;
    __dbsql_db_free(db, cte);
  }

  return p_new;
}

/*
** Free the contents of the with_t object passed as the second argument.
*/
void __with_delete(DBSQL *db, with_t *with){
  if( with ){
    int i;
    for(i=0; i<with->n_cte; i++){
      __cte_clear(db, &with->a[i]);
    }
    __dbsql_db_free(db, with);
  }
}
void __with_delete_generic(DBSQL *db, void *with){
  __with_delete(db, (with_t*)with);
}
