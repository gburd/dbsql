/*
** Return a key_info_t structure that is appropriate for the given index_t.
**
** The caller should invoke __key_info_unref() on the returned object
** when it has finished using it.
*/
key_info_t *__key_info_of_index(parser_t *parser, index_t *idx){
  int i;
  int n_col = idx->n_column;
  int n_key = idx->n_key_col;
  key_info_t *key;
  if( parser->n_err ) return 0;
  if( idx->uniq_not_null ){
    key = __key_info_alloc(parser->db, n_key, n_col-n_key);
  }else{
    key = __key_info_alloc(parser->db, n_col, 0);
  }
  if( key ){
    assert( __key_info_is_writeable(key) );
    for(i=0; i<n_col; i++){
      const char *coll = idx->colls[i];
      key->colls[i] = coll==__str_binary ? 0 :
                        __locate_coll_seq(parser, coll);
      key->sort_flags[i] = idx->sort_orders[i];
      assert( 0==(key->sort_flags[i] & KEYINFO_ORDER_BIGNULL) );
    }
    if( parser->n_err ){
      assert( parser->rc==DBSQL_ERROR_MISSING_COLLSEQ );
      if( idx->no_query==0 
       && __hash_find(&idx->schema->idx_hash, idx->name)
      ){
        /* Deactivate the index because it contains an unknown collating
        ** sequence.  The only way to reactive the index is to reload the
        ** schema.  Adding the missing collating sequence later does not
        ** reactive the index.  The application had the chance to register
        ** the missing index using the collation-needed callback.  For
        ** simplicity, dbsql will not give the application a second chance.
        **
        ** Except, do not do this if the index is not in the schema hash
        ** table. In this case the index is currently being constructed
        ** by a CREATE INDEX statement, and retrying will not help.  */
        idx->no_query = 1;
        parser->rc = DBSQL_ERROR_RETRY;
      }
      __key_info_unref(key);
      key = 0;
    }
  }
  return key;
}

