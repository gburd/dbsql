/*
** SELECT REWRITING
**
**   Any SELECT statement that contains one or more window functions in
**   either the select list or ORDER BY clause (the only two places window
**   functions may be used) is transformed by function __window_rewrite()
**   in order to support window function processing. For example, with the
**   schema:
**
**     CREATE TABLE t1(a, b, c, d, e, f, g);
**
**   the statement:
**
**     SELECT a+1, max(b) OVER (PARTITION BY c ORDER BY d) FROM t1 ORDER BY e;
**
**   is transformed to:
**
**     SELECT a+1, max(b) OVER (PARTITION BY c ORDER BY d) FROM (
**         SELECT a, e, c, d, b FROM t1 ORDER BY c, d
**     ) ORDER BY e;
**
**   The flattening optimization is disabled when processing this transformed
**   SELECT statement. This allows the implementation of the window function
**   (in this case max()) to process rows sorted in order of (c, d), which
**   makes things easier for obvious reasons. More generally:
**
**     * FROM, WHERE, GROUP BY and HAVING clauses are all moved to
**       the sub-query.
**
**     * ORDER BY, LIMIT and OFFSET remain part of the parent query.
**
**     * Terminals from each of the expression trees that make up the
**       select-list and ORDER BY expressions in the parent query are
**       selected by the sub-query. For the purposes of the transformation,
**       terminals are column references and aggregate functions.
**
**   If there is more than one window function in the SELECT that uses
**   the same window declaration (the OVER bit), then a single scan may
**   be used to process more than one window function. For example:
**
**     SELECT max(b) OVER (PARTITION BY c ORDER BY d),
**            min(e) OVER (PARTITION BY c ORDER BY d)
**     FROM t1;
**
**   is transformed in the same way as the example above. However:
**
**     SELECT max(b) OVER (PARTITION BY c ORDER BY d),
**            min(e) OVER (PARTITION BY a ORDER BY b)
**     FROM t1;
**
**   Must be transformed to:
**
**     SELECT max(b) OVER (PARTITION BY c ORDER BY d) FROM (
**         SELECT e, min(e) OVER (PARTITION BY a ORDER BY b), c, d, b FROM
**           SELECT a, e, c, d, b FROM t1 ORDER BY a, b
**         ) ORDER BY c, d
**     ) ORDER BY e;
**
**   so that both min() and max() may process rows in the order defined by
**   their respective window declarations.
**
** INTERFACE WITH SELECT.C
**
**   When processing the rewritten SELECT statement, code in select.c calls
**   __where_begin() to begin iterating through the results of the
**   sub-query, which is always implemented as a co-routine. It then calls
**   __window_code_step() to process rows and finish the scan by calling
**   __where_end().
**
**   __window_code_step() generates VM code so that, for each row returned
**   by the sub-query a sub-routine (OP_Gosub) coded by select.c is invoked.
**   When the sub-routine is invoked:
**
**     * The results of all window-functions for the row are stored
**       in the associated window_t.reg_result registers.
**
**     * The required terminal values are stored in the current row of
**       temp table window_t.i_eph_csr.
**
**   In some cases, depending on the window frame and the specific window
**   functions invoked, __window_code_step() caches each entire partition
**   in a temp table before returning any rows. In other cases it does not.
**   This detail is encapsulated within this file, the code generated by
**   select.c is the same in either case.
**
** BUILT-IN WINDOW FUNCTIONS
**
**   This implementation features the following built-in window functions:
**
**     row_number()
**     rank()
**     dense_rank()
**     percent_rank()
**     cume_dist()
**     ntile(N)
**     lead(expr [, offset [, default]])
**     lag(expr [, offset [, default]])
**     first_value(expr)
**     last_value(expr)
**     nth_value(expr, N)
**  
**   These are the same built-in window functions supported by Postgres.
**   Although the behaviour of aggregate window functions (functions that
**   can be used as either aggregates or window functions) allows them to
**   be implemented using an API, built-in window functions are much more
**   esoteric. Additionally, some window functions (e.g. nth_value())
**   may only be implemented by caching the entire partition in memory.
**   As such, some built-in window functions use the same API as aggregate
**   window functions and some are implemented directly using VDBE
**   instructions. Additionally, for those functions that use the API, the
**   window frame is sometimes modified before the SELECT statement is
**   rewritten. For example, regardless of the specified window frame, the
**   row_number() function always uses:
**
**     ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
**
**   See __window_update() for details.
**
**   As well as some of the built-in window functions, aggregate window
**   functions min() and max() are implemented using VDBE instructions if
**   the start of the window frame is declared as anything other than
**   UNBOUNDED PRECEDING.
*/

/*
** Implementation of built-in window function row_number(). Assumes that the
** window frame has been coerced to:
**
**   ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
*/
static void __row_number_step_func(
  dbsql_func_t *ctx,
  int n_arg,
  dbsql_value_t **args
){
  int64_t *p = (int64_t*)dbsql_aggregate_context(ctx, sizeof(*p));
  if( p ) (*p)++;
  UNUSED_PARAMETER(n_arg);
  UNUSED_PARAMETER(args);
}
static void __row_number_value_func(dbsql_func_t *ctx){
  int64_t *p = (int64_t*)dbsql_aggregate_context(ctx, sizeof(*p));
  dbsql_result_int64(ctx, (p ? *p : 0));
}

/*
** Context object type used by rank(), dense_rank(), percent_rank() and
** cume_dist().
*/
struct call_count_t {
  int64_t n_value;
  int64_t n_step;
  int64_t n_total;
};

/*
** Implementation of built-in window function dense_rank(). Assumes that
** the window frame has been set to:
**
**   RANGE BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
*/
static void __dense_rank_step_func(
  dbsql_func_t *ctx,
  int n_arg,
  dbsql_value_t **args
){
  struct call_count_t *p;
  p = (struct call_count_t*)dbsql_aggregate_context(ctx, sizeof(*p));
  if( p ) p->n_step = 1;
  UNUSED_PARAMETER(n_arg);
  UNUSED_PARAMETER(args);
}
static void __dense_rank_value_func(dbsql_func_t *ctx){
  struct call_count_t *p;
  p = (struct call_count_t*)dbsql_aggregate_context(ctx, sizeof(*p));
  if( p ){
    if( p->n_step ){
      p->n_value++;
      p->n_step = 0;
    }
    dbsql_result_int64(ctx, p->n_value);
  }
}

/*
** Implementation of built-in window function nth_value(). This
** implementation is used in "slow mode" only - when the EXCLUDE clause
** is not set to the default value "NO OTHERS".
*/
struct nth_value_ctx_t {
  int64_t n_step;
  dbsql_value_t *value;
};
static void __nth_value_step_func(
  dbsql_func_t *ctx,
  int n_arg,
  dbsql_value_t **args
){
  struct nth_value_ctx_t *p;
  p = (struct nth_value_ctx_t*)dbsql_aggregate_context(ctx, sizeof(*p));
  if( p ){
    int64_t i_val;
    switch( dbsql_value_numeric_type(args[1]) ){
      case DBSQL_INTEGER:
        i_val = dbsql_value_int64(args[1]);
        break;
      case DBSQL_FLOAT: {
        double f_val = dbsql_value_double(args[1]);
        if( __real_to_i64(f_val)!=f_val ) goto error_out;
        i_val = (int64_t)f_val;
        break;
      }
      default:
        goto error_out;
    }
    if( i_val<=0 ) goto error_out;

    p->n_step++;
    if( i_val==p->n_step ){
      p->value = dbsql_value_dup(args[0]);
      if( !p->value ){
        dbsql_result_error_nomem(ctx);
      }
    }
  }
  UNUSED_PARAMETER(n_arg);
  UNUSED_PARAMETER(args);
  return;

 error_out:
  dbsql_result_error(
      ctx, "second argument to nth_value must be a positive integer", -1
  );
}
static void __nth_value_finalize_func(dbsql_func_t *ctx){
  struct nth_value_ctx_t *p;
  p = (struct nth_value_ctx_t*)dbsql_aggregate_context(ctx, 0);
  if( p && p->value ){
    dbsql_result_value(ctx, p->value);
    dbsql_value_free(p->value);
    p->value = 0;
  }
}
#define __nth_value_inv_func __noop_step_func
#define __nth_value_value_func __noop_value_func

static void __first_value_step_func(
  dbsql_func_t *ctx,
  int n_arg,
  dbsql_value_t **args
){
  struct nth_value_ctx_t *p;
  p = (struct nth_value_ctx_t*)dbsql_aggregate_context(ctx, sizeof(*p));
  if( p && p->value==0 ){
    p->value = dbsql_value_dup(args[0]);
    if( !p->value ){
      dbsql_result_error_nomem(ctx);
    }
  }
  UNUSED_PARAMETER(n_arg);
  UNUSED_PARAMETER(args);
}
static void __first_value_finalize_func(dbsql_func_t *ctx){
  struct nth_value_ctx_t *p;
  p = (struct nth_value_ctx_t*)dbsql_aggregate_context(ctx, sizeof(*p));
  if( p && p->value ){
    dbsql_result_value(ctx, p->value);
    dbsql_value_free(p->value);
    p->value = 0;
  }
}
#define __first_value_inv_func __noop_step_func
#define __first_value_value_func __noop_value_func

/*
** Implementation of built-in window function rank(). Assumes that
** the window frame has been set to:
**
**   RANGE BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
*/
static void __rank_step_func(
  dbsql_func_t *ctx,
  int n_arg,
  dbsql_value_t **args
){
  struct call_count_t *p;
  p = (struct call_count_t*)dbsql_aggregate_context(ctx, sizeof(*p));
  if( p ){
    p->n_step++;
    if( p->n_value==0 ){
      p->n_value = p->n_step;
    }
  }
  UNUSED_PARAMETER(n_arg);
  UNUSED_PARAMETER(args);
}
static void __rank_value_func(dbsql_func_t *ctx){
  struct call_count_t *p;
  p = (struct call_count_t*)dbsql_aggregate_context(ctx, sizeof(*p));
  if( p ){
    dbsql_result_int64(ctx, p->n_value);
    p->n_value = 0;
  }
}

/*
** Implementation of built-in window function percent_rank(). Assumes that
** the window frame has been set to:
**
**   GROUPS BETWEEN CURRENT ROW AND UNBOUNDED FOLLOWING
*/
static void __percent_rank_step_func(
  dbsql_func_t *ctx,
  int n_arg,
  dbsql_value_t **args
){
  struct call_count_t *p;
  UNUSED_PARAMETER(n_arg); assert( n_arg==0 );
  UNUSED_PARAMETER(args);
  p = (struct call_count_t*)dbsql_aggregate_context(ctx, sizeof(*p));
  if( p ){
    p->n_total++;
  }
}
static void __percent_rank_inv_func(
  dbsql_func_t *ctx,
  int n_arg,
  dbsql_value_t **args
){
  struct call_count_t *p;
  UNUSED_PARAMETER(n_arg); assert( n_arg==0 );
  UNUSED_PARAMETER(args);
  p = (struct call_count_t*)dbsql_aggregate_context(ctx, sizeof(*p));
  p->n_step++;
}
static void __percent_rank_value_func(dbsql_func_t *ctx){
  struct call_count_t *p;
  p = (struct call_count_t*)dbsql_aggregate_context(ctx, sizeof(*p));
  if( p ){
    p->n_value = p->n_step;
    if( p->n_total>1 ){
      double r = (double)p->n_value / (double)(p->n_total-1);
      dbsql_result_double(ctx, r);
    }else{
      dbsql_result_double(ctx, 0.0);
    }
  }
}
#define __percent_rank_finalize_func __percent_rank_value_func

