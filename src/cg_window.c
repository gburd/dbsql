/*
** Context object for ntile() window function.
*/
struct ntile_ctx_t {
  int64_t n_total;                     /* Total rows in partition */
  int64_t n_param;                     /* Parameter passed to ntile(N) */
  int64_t i_row;                       /* Current row */
};

/*
** Implementation of ntile(). This assumes that the window frame has
** been coerced to:
**
**   ROWS CURRENT ROW AND UNBOUNDED FOLLOWING
*/
static void __ntile_step_func(
  dbsql_func_t *ctx,
  int n_arg,
  dbsql_value_t **args
){
  struct ntile_ctx_t *p;
  assert( n_arg==1 ); UNUSED_PARAMETER(n_arg);
  p = (struct ntile_ctx_t*)dbsql_aggregate_context(ctx, sizeof(*p));
  if( p ){
    if( p->n_total==0 ){
      p->n_param = dbsql_value_int64(args[0]);
      if( p->n_param<=0 ){
        dbsql_result_error(
            ctx, "argument of ntile must be a positive integer", -1
        );
      }
    }
    p->n_total++;
  }
}
static void __ntile_inv_func(
  dbsql_func_t *ctx,
  int n_arg,
  dbsql_value_t **args
){
  struct ntile_ctx_t *p;
  assert( n_arg==1 ); UNUSED_PARAMETER(n_arg);
  UNUSED_PARAMETER(args);
  p = (struct ntile_ctx_t*)dbsql_aggregate_context(ctx, sizeof(*p));
  p->i_row++;
}
static void __ntile_value_func(dbsql_func_t *ctx){
  struct ntile_ctx_t *p;
  p = (struct ntile_ctx_t*)dbsql_aggregate_context(ctx, sizeof(*p));
  if( p && p->n_param>0 ){
    int n_size = (p->n_total / p->n_param);
    if( n_size==0 ){
      dbsql_result_int64(ctx, p->i_row+1);
    }else{
      int64_t n_large = p->n_total - p->n_param*n_size;
      int64_t i_small = n_large*(n_size+1);
      int64_t i_row = p->i_row;

      assert( (n_large*(n_size+1) + (p->n_param-n_large)*n_size)==p->n_total );

      if( i_row<i_small ){
        dbsql_result_int64(ctx, 1 + i_row/(n_size+1));
      }else{
        dbsql_result_int64(ctx, 1 + n_large + (i_row-i_small)/n_size);
      }
    }
  }
}
#define __ntile_finalize_func __ntile_value_func

/*
** Context object for last_value() window function.
*/
struct last_value_ctx_t {
  dbsql_value_t *val;
  int n_val;
};

/*
** Implementation of last_value().
*/
static void __last_value_step_func(
  dbsql_func_t *ctx,
  int n_arg,
  dbsql_value_t **args
){
  struct last_value_ctx_t *p;
  UNUSED_PARAMETER(n_arg);
  p = (struct last_value_ctx_t*)dbsql_aggregate_context(ctx, sizeof(*p));
  if( p ){
    dbsql_value_free(p->val);
    p->val = dbsql_value_dup(args[0]);
    if( p->val==0 ){
      dbsql_result_error_nomem(ctx);
    }else{
      p->n_val++;
    }
  }
}
static void __last_value_inv_func(
  dbsql_func_t *ctx,
  int n_arg,
  dbsql_value_t **args
){
  struct last_value_ctx_t *p;
  UNUSED_PARAMETER(n_arg);
  UNUSED_PARAMETER(args);
  p = (struct last_value_ctx_t*)dbsql_aggregate_context(ctx, sizeof(*p));
  if( ALWAYS(p) ){
    p->n_val--;
    if( p->n_val==0 ){
      dbsql_value_free(p->val);
      p->val = 0;
    }
  }
}
static void __last_value_value_func(dbsql_func_t *ctx){
  struct last_value_ctx_t *p;
  p = (struct last_value_ctx_t*)dbsql_aggregate_context(ctx, 0);
  if( p && p->val ){
    dbsql_result_value(ctx, p->val);
  }
}
static void __last_value_finalize_func(dbsql_func_t *ctx){
  struct last_value_ctx_t *p;
  p = (struct last_value_ctx_t*)dbsql_aggregate_context(ctx, sizeof(*p));
  if( p && p->val ){
    dbsql_result_value(ctx, p->val);
    dbsql_value_free(p->val);
    p->val = 0;
  }
}

