/*
** This is called during initialization to register the fts5_expr() scalar
** UDF with the dbsql handle passed as the only argument.
*/
int __fts5_expr_init(fts5_global_t *__p_global, DBSQL *db){
#if defined(DBSQL_TEST) || defined(DBSQL_FTS5_DEBUG)
  struct fts5_expr_func_t {
    const char *z;
    void (*x)(dbsql_func_t*,int,dbsql_value_t**);
  } funcs[] = {
    { "fts5_expr",     __fts5_expr_function_hr },
    { "fts5_expr_tcl", __fts5_expr_function_tcl },
    { "fts5_isalnum",  __fts5_expr_is_alnum },
    { "fts5_fold",     __fts5_expr_fold },
  };
  int i;
  int rc = DBSQL_OK;
  void *ctx = (void*)__p_global;

  for(i=0; rc==DBSQL_OK && i<ARRAY_SIZE(funcs); i++){
    struct fts5_expr_func_t *p = &funcs[i];
    rc = dbsql_create_function(db, p->z, -1, DBSQL_UTF8, ctx, p->x, 0, 0);
  }
#else
  int rc = DBSQL_OK;
  UNUSED_PARAM2(__p_global,db);
#endif

  /* Avoid warnings indicating that fts5_parserTrace() and
  ** fts5_parserFallback() are unused */
#ifndef NDEBUG
  (void)fts5_parserTrace;
#endif
  (void)fts5_parserFallback;

  return rc;
}

/*
** Return the number of phrases in expression expr.
*/
int __fts5_expr_phrase_count(fts5_expr_t *expr){
  return (expr ? expr->n_phrase : 0);
}

/*
** Return the number of terms in the i_phrase'th phrase in expr.
*/
int __fts5_expr_phrase_size(fts5_expr_t *expr, int i_phrase){
  if( i_phrase<0 || i_phrase>=expr->n_phrase ) return 0;
  return expr->expr_phrases[i_phrase]->n_term;
}

/*
** This function is used to access the current position list for phrase
** i_phrase.
*/
int __fts5_expr_poslist(fts5_expr_t *expr, int i_phrase, const u_int8_t **pa){
  int n_ret;
  fts5_expr_phrase_t *phrase = expr->expr_phrases[i_phrase];
  fts5_expr_node_t *node = phrase->node;
  if( node->eof==0 && node->i_rowid==expr->root->i_rowid ){
    *pa = phrase->poslist.p;
    n_ret = phrase->poslist.n;
  }else{
    *pa = 0;
    n_ret = 0;
  }
  return n_ret;
}

struct fts5_poslist_populator_t {
  fts5_poslist_writer_t writer;
  int ok;                        /* True if ok to populate */
  int miss;
};

/*
** Clear the position lists associated with all phrases in the expression
** passed as the first argument. Argument live is true if the expression
** might be pointing to a real entry, otherwise it has just been reset.
**
** At present this function is only used for detail=col and detail=none
** fts5 tables. This implies that all phrases must be at most 1 token
** in size, as phrase matches are not supported without detail=full.
*/
fts5_poslist_populator_t *__fts5_expr_clear_poslists(fts5_expr_t *expr, int live){
  fts5_poslist_populator_t *ret;
  ret = dbsql_malloc64(sizeof(fts5_poslist_populator_t)*expr->n_phrase);
  if( ret ){
    int i;
    memset(ret, 0, sizeof(fts5_poslist_populator_t)*expr->n_phrase);
    for(i=0; i<expr->n_phrase; i++){
      fts5_buffer_t *buf = &expr->expr_phrases[i]->poslist;
      fts5_expr_node_t *node = expr->expr_phrases[i]->node;
      assert( expr->expr_phrases[i]->n_term<=1 );
      if( live && 
          (buf->n==0 || node->i_rowid!=expr->root->i_rowid || node->eof)
      ){
        ret[i].miss = 1;
      }else{
        buf->n = 0;
      }
    }
  }
  return ret;
}

struct fts5_expr_ctx_t {
  fts5_expr_t *expr;
  fts5_poslist_populator_t *populators;
  int64_t i_off;
};
typedef struct fts5_expr_ctx_t fts5_expr_ctx_t;

/*
** TODO: Make this more efficient!
*/
static int __fts5_expr_colset_test(fts5_colset_t *colset, int i_col){
  int i;
  for(i=0; i<colset->n_col; i++){
    if( colset->cols[i]==i_col ) return 1;
  }
  return 0;
}

/*
** token is a buffer n_token bytes in size that may or may not contain
** an embedded 0x00 byte. If it does, return the number of bytes in
** the buffer before the 0x00. If it does not, return n_token.
*/
static int __fts5_query_term(const char *token, int n_token){
  int ii;
  for(ii=0; ii<n_token && token[ii]; ii++){}
  return ii;
}

static int __fts5_expr_populate_poslists_cb(
  void *ctx,                /* Copy of 2nd argument to tokenize() */
  int tflags,                /* Mask of FTS5_TOKEN_* flags */
  const char *token,        /* Pointer to buffer containing token */
  int n_token,                /* Size of token in bytes */
  int i_unused1,              /* Byte offset of token within input text */
  int i_unused2               /* Byte offset of end of token within input text */
){
  fts5_expr_ctx_t *p = (fts5_expr_ctx_t*)ctx;
  fts5_expr_t *expr = p->expr;
  int i;
  int n_query = n_token;
  int64_t i_rowid = expr->root->i_rowid;

  UNUSED_PARAM2(i_unused1, i_unused2);

  if( n_query>FTS5_MAX_TOKEN_SIZE ) n_query = FTS5_MAX_TOKEN_SIZE;
  if( expr->config->tokendata ){
    n_query = __fts5_query_term(token, n_query);
  }
  if( (tflags & FTS5_TOKEN_COLOCATED)==0 ) p->i_off++;
  for(i=0; i<expr->n_phrase; i++){
    fts5_expr_term_t *t;
    if( p->populators[i].ok==0 ) continue;
    for(t=&expr->expr_phrases[i]->terms[0]; t; t=t->synonym){
      if( (t->n_query_term==n_query || (t->n_query_term<n_query && t->prefix))
       && memcmp(t->term, token, t->n_query_term)==0
      ){
        int rc = __fts5_poslist_writer_append(
            &expr->expr_phrases[i]->poslist, &p->populators[i].writer, p->i_off
        );
        if( rc==DBSQL_OK && (expr->config->tokendata || t->prefix) ){
          int i_col = p->i_off>>32;
          int i_tok_off = p->i_off & 0x7FFFFFFF;
          rc = __fts5_index_iter_write_tokendata(
              t->iter, token, n_token, i_rowid, i_col, i_tok_off
          );
        }
        if( rc ) return rc;
        break;
      }
    }
  }
  return DBSQL_OK;
}

int __fts5_expr_populate_poslists(
  fts5_config_t *config,
  fts5_expr_t *expr, 
  fts5_poslist_populator_t *populators,
  int i_col, 
  const char *z, int n
){
  int i;
  fts5_expr_ctx_t s_ctx;
  s_ctx.expr = expr;
  s_ctx.populators = populators;
  s_ctx.i_off = (((int64_t)i_col) << 32) - 1;

  for(i=0; i<expr->n_phrase; i++){
    fts5_expr_node_t *node = expr->expr_phrases[i]->node;
    fts5_colset_t *colset = node->near->colset;
    if( (colset && 0==__fts5_expr_colset_test(colset, i_col)) 
     || populators[i].miss
    ){
      populators[i].ok = 0;
    }else{
      populators[i].ok = 1;
    }
  }

  return __fts5_tokenize(config, 
      FTS5_TOKENIZE_DOCUMENT, z, n, (void*)&s_ctx, __fts5_expr_populate_poslists_cb
  );
}

static void __fts5_expr_clear_poslists_local(fts5_expr_node_t *node){
  if( node->type==FTS5_TERM || node->type==FTS5_STRING ){
    node->near->phrases[0]->poslist.n = 0;
  }else{
    int i;
    for(i=0; i<node->n_child; i++){
      __fts5_expr_clear_poslists_local(node->childs[i]);
    }
  }
}

static int __fts5_expr_check_poslists_local(fts5_expr_node_t *node, int64_t i_rowid){
  node->i_rowid = i_rowid;
  node->eof = 0;
  switch( node->type ){
    case 0:
    case FTS5_TERM:
    case FTS5_STRING:
      return (node->near->phrases[0]->poslist.n>0);

    case FTS5_AND: {
      int i;
      for(i=0; i<node->n_child; i++){
        if( __fts5_expr_check_poslists_local(node->childs[i], i_rowid)==0 ){
          __fts5_expr_clear_poslists_local(node);
          return 0;
        }
      }
      break;
    }

    case FTS5_OR: {
      int i;
      int ret = 0;
      for(i=0; i<node->n_child; i++){
        if( __fts5_expr_check_poslists_local(node->childs[i], i_rowid) ){
          ret = 1;
        }
      }
      return ret;
    }

    default: {
      assert( node->type==FTS5_NOT );
      if( 0==__fts5_expr_check_poslists_local(node->childs[0], i_rowid)
          || 0!=__fts5_expr_check_poslists_local(node->childs[1], i_rowid)
        ){
        __fts5_expr_clear_poslists_local(node);
        return 0;
      }
      break;
    }
  }
  return 1;
}

void __fts5_expr_check_poslists(fts5_expr_t *expr, int64_t i_rowid){
  __fts5_expr_check_poslists_local(expr->root, i_rowid);
}

/*
** This function is only called for detail=columns tables. 
*/
int __fts5_expr_phrase_collist(
  fts5_expr_t *expr, 
  int i_phrase, 
  const u_int8_t **collist, 
  int *pn_collist
){
  fts5_expr_phrase_t *phrase = expr->expr_phrases[i_phrase];
  fts5_expr_node_t *node = phrase->node;
  int rc = DBSQL_OK;

  assert( i_phrase>=0 && i_phrase<expr->n_phrase );
  assert( expr->config->detail==FTS5_DETAIL_COLUMNS );

  if( node->eof==0 
   && node->i_rowid==expr->root->i_rowid 
   && phrase->poslist.n>0
  ){
    fts5_expr_term_t *term = &phrase->terms[0];
    if( term->synonym ){
      fts5_buffer_t *buf = (fts5_buffer_t*)&term->synonym[1];
      rc = __fts5_expr_synonym_list(
          term, node->i_rowid, buf, (u_int8_t**)collist, pn_collist
      );
    }else{
      *collist = phrase->terms[0].iter->data;
      *pn_collist = phrase->terms[0].iter->n_data;
    }
  }else{
    *collist = 0;
    *pn_collist = 0;
  }

  return rc;
}

/*
** Does the work of the fts5_api.query_token() API method.
*/
int __fts5_expr_query_token(
  fts5_expr_t *expr, 
  int i_phrase, 
  int i_token, 
  const char **out, 
  int *pn_out
){
  fts5_expr_phrase_t *phrase = 0;

  if( i_phrase<0 || i_phrase>=expr->n_phrase ){
    return DBSQL_RANGE;
  }
  phrase = expr->expr_phrases[i_phrase];
  if( i_token<0 || i_token>=phrase->n_term ){
    return DBSQL_RANGE;
  }

  *out = phrase->terms[i_token].term;
  *pn_out = phrase->terms[i_token].n_full_term;
  return DBSQL_OK;
}

/*
** Does the work of the fts5_api.inst_token() API method.
*/
int __fts5_expr_inst_token(
  fts5_expr_t *expr, 
  int64_t i_rowid,
  int i_phrase, 
  int i_col, 
  int i_off, 
  int i_token, 
  const char **out, 
  int *pn_out
){
  fts5_expr_phrase_t *phrase = 0;
  fts5_expr_term_t *term = 0;
  int rc = DBSQL_OK;

  if( i_phrase<0 || i_phrase>=expr->n_phrase ){
    return DBSQL_RANGE;
  }
  phrase = expr->expr_phrases[i_phrase];
  if( i_token<0 || i_token>=phrase->n_term ){
    return DBSQL_RANGE;
  }
  term = &phrase->terms[i_token];
  if( expr->config->tokendata || term->prefix ){
    rc = __fts5_iter_token(
        term->iter, term->term, term->n_query_term, 
        i_rowid, i_col, i_off+i_token, out, pn_out
    );
  }else{
    *out = term->term;
    *pn_out = term->n_full_term;
  }
  return rc;
}

/*
** Clear the token mappings for all fts5_index_iter_t objects managed by 
** the expression passed as the only argument.
*/
void __fts5_expr_clear_tokens(fts5_expr_t *expr){
  int ii;
  for(ii=0; ii<expr->n_phrase; ii++){
    fts5_expr_term_t *t;
    for(t=&expr->expr_phrases[ii]->terms[0]; t; t=t->synonym){
      __fts5_index_iter_clear_tokendata(t->iter);
    }
  }
}
