/*
 * Supplementary token definitions for modern SQL features.
 *
 * These tokens are required by the tokenizer for SQLite 3.52.0
 * compatible keyword recognition.  They extend the base token set
 * defined in sql_parser.h (which is generated by lemon from
 * sql_parser.y).
 *
 * When the grammar (sql_parser.y) is updated to support these
 * features, the corresponding TK_ definitions will move into the
 * generated sql_parser.h and should be removed from this file.
 *
 * Token numbers start at 200 to avoid colliding with the
 * lemon-generated values in sql_parser.h (which currently go
 * up to ~130).
 */

