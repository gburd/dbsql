/*
** The VDBE_COVERAGE macros are used to set a coverage testing point
** for VDBE branch instructions.  The coverage testing points are line
** numbers in the DBSQL.c source file.  VDBE branch coverage testing
** only works with an amalgamation build.  That's ok since a VDBE branch
** coverage build designed for testing the test suite only.  No application
** should ever ship with VDBE branch coverage measuring turned on.
**
**    VDBE_COVERAGE(v)                  // Mark the previously coded instruction
**                                     // as a branch
**
**    VDBE_COVERAGE_IF(v, conditional)   // Mark previous if conditional true
**
**    VDBE_COVERAGE_ALWAYS_TAKEN(v)       // Previous branch is always taken
**
**    VDBE_COVERAGE_NEVER_TAKEN(v)        // Previous branch is never taken
**
**    VDBE_COVERAGE_NEVER_NULL(v)         // Previous three-way branch is only
**                                     // taken on the first two ways.  The
**                                     // NULL option is not possible
**
**    VDBE_COVERAGE_EQ_NE(v)              // Previous OP_Jump is only interested
**                                     // in distinguishing equal and not-equal.
**
** Every VDBE branch operation must be tagged with one of the macros above.
** If not, then when "make test" is run with -DSQLITE_VDBE_COVERAGE and
** -DSQLITE_DEBUG then an ALWAYS() will fail in the __vdbe_take_branch()
** routine in vdbe.c, alerting the developer to the missed tag.
**
** During testing, the test application will invoke
** dbsql_test_control(DBSQL_TESTCTRL_VDBE_COVERAGE,...) to set a callback
** routine that is invoked as each bytecode branch is taken.  The callback
** contains the DBSQL.c source line number of the VDBE_COVERAGE macro and
** flags to indicate whether or not the branch was taken.  The test application
** is responsible for keeping track of this and reporting byte-code branches
** that are never taken.
**
** See the VDBE_BRANCH_TAKEN() macro and __vdbe_take_branch() function in the
** vdbe.c source file for additional information.
*/
#ifdef DBSQL_VDBE_COVERAGE
  void __vdbe_set_line_number(vdbe_t*,int);
# define VDBE_COVERAGE(v) __vdbe_set_line_number(v,__LINE__)
# define VDBE_COVERAGE_IF(v,x) if(x)__vdbe_set_line_number(v,__LINE__)
# define VDBE_COVERAGE_ALWAYS_TAKEN(v) \
         __vdbe_set_line_number(v,__LINE__|0x5000000);
# define VDBE_COVERAGE_NEVER_TAKEN(v) \
         __vdbe_set_line_number(v,__LINE__|0x6000000);
# define VDBE_COVERAGE_NEVER_NULL(v) \
         __vdbe_set_line_number(v,__LINE__|0x4000000);
# define VDBE_COVERAGE_NEVER_NULL_IF(v,x) \
         if(x)__vdbe_set_line_number(v,__LINE__|0x4000000);
# define VDBE_COVERAGE_EQ_NE(v) \
         __vdbe_set_line_number(v,__LINE__|0x8000000);
# define VDBE_OFFSET_LINENO(x) (__LINE__+x)
#else
# define VDBE_COVERAGE(v)
# define VDBE_COVERAGE_IF(v,x)
# define VDBE_COVERAGE_ALWAYS_TAKEN(v)
# define VDBE_COVERAGE_NEVER_TAKEN(v)
# define VDBE_COVERAGE_NEVER_NULL(v)
# define VDBE_COVERAGE_NEVER_NULL_IF(v,x)
# define VDBE_COVERAGE_EQ_NE(v)
# define VDBE_OFFSET_LINENO(x) 0
#endif

